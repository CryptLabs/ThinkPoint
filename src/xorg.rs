//! Generating an X server configuration snippet.
//!
//! The profile written by `persist` needs `--restore` to run at session start
//! before it does anything. An xorg.conf.d snippet needs nothing: the X server
//! reads it when it creates the device, which covers a reboot and a device
//! being re-plugged, with no autostart hook anywhere.
//!
//! The cost is that it is not a complete substitute. Only settings with a
//! driver option equivalent can be expressed, it needs root to write, and it
//! takes effect when the X server next starts rather than immediately. Where a
//! setting has no equivalent, the snippet says so in a comment rather than
//! quietly dropping it.

use crate::persist::XSetting;

pub const XORG_PATH: &str = "/etc/X11/xorg.conf.d/50-thinkpoint.conf";

/// libinput properties that have an `Option` in xf86-input-libinput.
///
/// The multi-valued ones — scroll method, acceleration profile — are handled
/// separately below, since a list of flags has to become a single word.
const BOOLEAN_OPTIONS: &[(&str, &str)] = &[
    ("libinput Natural Scrolling Enabled", "NaturalScrolling"),
    ("libinput Middle Emulation Enabled", "MiddleEmulation"),
    ("libinput Left Handed Enabled", "LeftHanded"),
    ("libinput Tapping Enabled", "Tapping"),
    ("libinput Tapping Drag Enabled", "TappingDrag"),
    ("libinput Tapping Drag Lock Enabled", "TappingDragLock"),
    (
        "libinput Disable While Typing Enabled",
        "DisableWhileTyping",
    ),
    ("libinput Horizontal Scroll Enabled", "HorizontalScrolling"),
    ("libinput Scroll Button Lock Enabled", "ScrollButtonLock"),
];

const NUMERIC_OPTIONS: &[(&str, &str)] = &[
    ("libinput Accel Speed", "AccelSpeed"),
    ("libinput Button Scrolling Button", "ScrollButton"),
    ("libinput Scrolling Pixel Distance", "ScrollPixelDistance"),
    ("libinput Rotation Angle", "RotationAngle"),
];

const SCROLL_METHOD: &str = "libinput Scroll Method Enabled";
const ACCEL_PROFILE: &str = "libinput Accel Profile Enabled";

fn flag(value: &str) -> &'static str {
    if value == "1" { "true" } else { "false" }
}

/// Turn a property into one or more `Option` lines, or report that it has no
/// equivalent.
fn option_lines(name: &str, values: &[String]) -> Result<Vec<String>, String> {
    if let Some((_, option)) = BOOLEAN_OPTIONS.iter().find(|(prop, _)| *prop == name) {
        let Some(value) = values.first() else {
            return Err(name.to_string());
        };
        return Ok(vec![format!(r#"    Option "{option}" "{}""#, flag(value))]);
    }

    if let Some((_, option)) = NUMERIC_OPTIONS.iter().find(|(prop, _)| *prop == name) {
        let Some(value) = values.first() else {
            return Err(name.to_string());
        };
        return Ok(vec![format!(r#"    Option "{option}" "{value}""#)]);
    }

    // [two-finger, edge, button] becomes the one method that is switched on.
    if name == SCROLL_METHOD {
        let method = match (values.first(), values.get(1), values.get(2)) {
            (Some(t), _, _) if t == "1" => "twofinger",
            (_, Some(e), _) if e == "1" => "edge",
            (_, _, Some(b)) if b == "1" => "button",
            _ => "none",
        };
        return Ok(vec![format!(r#"    Option "ScrollMethod" "{method}""#)]);
    }

    // [adaptive, flat].
    if name == ACCEL_PROFILE {
        let profile = match (values.first(), values.get(1)) {
            (Some(a), _) if a == "1" => "adaptive",
            (_, Some(f)) if f == "1" => "flat",
            _ => return Err(name.to_string()),
        };
        return Ok(vec![format!(r#"    Option "AccelProfile" "{profile}""#)]);
    }

    Err(name.to_string())
}

/// The snippet for the given settings.
///
/// Device names come from the X server and are matched back against it, so
/// they are written as-is; a name containing a quote would be malformed, and
/// such a device is skipped rather than producing a broken config.
pub fn snippet(settings: &[XSetting]) -> String {
    let mut out = String::new();
    out.push_str("# Generated by thinkpoint. Edit freely; it is not rewritten\n");
    out.push_str("# unless you save from the tool again.\n");
    out.push_str("#\n");
    out.push_str("# Unlike the profile, nothing has to replay this: the X server reads it\n");
    out.push_str("# when it creates the device. It takes effect at the next X start.\n\n");

    let mut wrote_any = false;

    for setting in settings {
        if setting.device.contains('"') {
            continue;
        }

        let mut options: Vec<String> = Vec::new();
        let mut unsupported: Vec<String> = Vec::new();

        if let Some(map) = &setting.button_map {
            let joined: Vec<String> = map.iter().map(|b| b.to_string()).collect();
            options.push(format!(
                r#"    Option "ButtonMapping" "{}""#,
                joined.join(" ")
            ));
        }
        if setting.enabled == Some(false) {
            options.push(r#"    Option "SendEventsMode" "disabled""#.to_string());
        }
        for (name, values) in &setting.props {
            match option_lines(name, values) {
                Ok(lines) => options.extend(lines),
                Err(name) => unsupported.push(name),
            }
        }

        if options.is_empty() && unsupported.is_empty() {
            continue;
        }
        wrote_any = true;

        out.push_str("Section \"InputClass\"\n");
        out.push_str(&format!(
            "    Identifier  \"ThinkPoint {}\"\n",
            setting.device
        ));
        out.push_str("    MatchDriver \"libinput\"\n");
        out.push_str(&format!("    MatchProduct \"{}\"\n", setting.device));
        for option in &options {
            out.push_str(option);
            out.push('\n');
        }
        for name in &unsupported {
            // Said out loud, because a silently dropped setting looks like the
            // snippet covers everything when it does not.
            out.push_str(&format!(
                "    # no xorg option for {name} — it stays in the profile\n"
            ));
        }
        out.push_str("EndSection\n\n");
    }

    if !wrote_any {
        out.push_str("# Nothing to persist: no X settings have been changed.\n");
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn setting() -> XSetting {
        XSetting {
            device: "TPPS/2 Elan TrackPoint".to_string(),
            enabled: None,
            button_map: None,
            props: Vec::new(),
        }
    }

    #[test]
    fn a_button_map_becomes_a_button_mapping_option() {
        let mut s = setting();
        s.button_map = Some(vec![1, 0, 3, 4, 5, 6, 7]);
        let out = snippet(&[s]);
        assert!(
            out.contains(r#"Option "ButtonMapping" "1 0 3 4 5 6 7""#),
            "{out}"
        );
        assert!(out.contains(r#"MatchProduct "TPPS/2 Elan TrackPoint""#));
        assert!(out.contains(r#"MatchDriver "libinput""#));
    }

    #[test]
    fn a_disabled_device_stops_sending_events() {
        let mut s = setting();
        s.enabled = Some(false);
        assert!(snippet(&[s]).contains(r#"Option "SendEventsMode" "disabled""#));
    }

    #[test]
    fn an_enabled_device_needs_no_option() {
        let mut s = setting();
        s.enabled = Some(true);
        assert!(!snippet(&[s]).contains("SendEventsMode"));
    }

    #[test]
    fn booleans_become_true_and_false_rather_than_one_and_zero() {
        let mut s = setting();
        s.props = vec![(
            "libinput Natural Scrolling Enabled".into(),
            vec!["1".into()],
        )];
        assert!(snippet(&[s]).contains(r#"Option "NaturalScrolling" "true""#));
    }

    #[test]
    fn the_scroll_method_flags_become_one_word() {
        let mut s = setting();
        s.props = vec![(
            SCROLL_METHOD.into(),
            vec!["0".into(), "0".into(), "1".into()],
        )];
        assert!(snippet(&[s]).contains(r#"Option "ScrollMethod" "button""#));

        let mut off = setting();
        off.props = vec![(
            SCROLL_METHOD.into(),
            vec!["0".into(), "0".into(), "0".into()],
        )];
        assert!(snippet(&[off]).contains(r#"Option "ScrollMethod" "none""#));
    }

    #[test]
    fn accel_speed_is_passed_through() {
        let mut s = setting();
        s.props = vec![("libinput Accel Speed".into(), vec!["-0.300000".into()])];
        assert!(snippet(&[s]).contains(r#"Option "AccelSpeed" "-0.300000""#));
    }

    #[test]
    fn a_property_with_no_equivalent_is_named_rather_than_dropped() {
        let mut s = setting();
        s.props = vec![("libinput Calibration Matrix".into(), vec!["1".into()])];
        let out = snippet(&[s]);
        assert!(
            out.contains("no xorg option for libinput Calibration Matrix"),
            "{out}"
        );
        assert!(out.contains("it stays in the profile"));
    }

    #[test]
    fn nothing_changed_says_so() {
        assert!(snippet(&[]).contains("Nothing to persist"));
        assert!(!snippet(&[]).contains("Section"));
    }

    #[test]
    fn a_device_name_with_a_quote_is_skipped_rather_than_malformed() {
        let mut s = setting();
        s.device = "Odd \" Device".to_string();
        s.button_map = Some(vec![1, 0, 3]);
        assert!(!snippet(&[s]).contains("Section"));
    }

    #[test]
    fn several_devices_each_get_a_section() {
        let mut a = setting();
        a.button_map = Some(vec![1, 0, 3]);
        let mut b = setting();
        b.device = "SynPS/2 Synaptics TouchPad".into();
        b.enabled = Some(false);

        let out = snippet(&[a, b]);
        assert_eq!(out.matches("Section \"InputClass\"").count(), 2);
        assert!(out.contains("SynPS/2 Synaptics TouchPad"));
    }
}
